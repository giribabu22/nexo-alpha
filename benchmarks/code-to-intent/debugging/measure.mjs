#!/usr/bin/env node
/**
 * Runs every debugging scenario in both variants and writes DEBUGGING.md.
 *
 *   pnpm --filter @nexo/benchmark-code-to-intent build
 *   pnpm --filter @nexo/benchmark-code-to-intent measure:debugging
 *
 * It measures what the framework tells a developer, not how long a person
 * takes: see TIME-PROTOCOL.md for that.
 */

import { mkdtemp, rm, writeFile } from "node:fs/promises";
import { createServer } from "node:net";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { SCENARIOS, STAGES, score } from "./scenarios.mjs";

const here = dirname(fileURLToPath(import.meta.url));

async function freePort() {
  const probe = createServer();
  await new Promise((resolve) => probe.listen(0, "localhost", resolve));
  const { port } = probe.address();
  await new Promise((resolve) => probe.close(resolve));
  return port;
}

/** Runs one scenario's variant in a fresh directory, on a fresh port. */
export async function runScenario(scenario, variant) {
  const dir = await mkdtemp(join(tmpdir(), `nexo-debugging-${scenario.id}-`));
  const ctx = { dir, port: await freePort() };
  const secret = process.env.AUTH_SECRET;
  delete process.env.AUTH_SECRET;
  try {
    await scenario.setup?.(ctx);
    const outcome = await scenario[variant](ctx);
    return score(scenario, outcome, ctx);
  } finally {
    await scenario.teardown?.(ctx);
    if (secret !== undefined) process.env.AUTH_SECRET = secret;
    await rm(dir, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
  }
}

export async function runAll() {
  const results = [];
  for (const scenario of SCENARIOS) {
    results.push({ scenario, before: await runScenario(scenario, "before"), after: await runScenario(scenario, "after") });
  }
  return results;
}

const STAGE_TEXT = { startup: "at startup", request: "on the request", check: "by `nexo migrate check`", none: "not detected" };
const marks = (r) => ["cause", "where", "fix"].map((k) => (r.met[k] ? k : `~~${k}~~`)).join(" ");
const clip = (text) => {
  const one = text.replace(/\s+/g, " ").trim();
  return one.length > 400 ? `${one.slice(0, 400)}…` : one;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.env.NODE_ENV = "test";
  const results = await runAll();
  const total = (variant) => results.reduce((sum, r) => sum + r[variant].points, 0);
  const detected = (variant) => results.filter((r) => r[variant].stage !== "none").length;
  const earliest = (variant) => results.filter((r) => r[variant].stage === "startup").length;

  const rows = results.map(({ scenario, before, after }) =>
    `| ${scenario.title} (${scenario.kind}) | ${STAGE_TEXT[before.stage]}, ${before.points}/3 | ${STAGE_TEXT[after.stage]}, ${after.points}/3 |`
  );
  const details = results.map(({ scenario, before, after }) =>
    [
      `### ${scenario.title}`,
      "",
      `- **before** (${STAGE_TEXT[before.stage]}; ${marks(before)}): ${clip(before.message) || "(empty)"}`,
      `- **after** (${STAGE_TEXT[after.stage]}; ${marks(after)}): ${clip(after.message) || "(empty)"}`,
      ""
    ].join("\n")
  );

  const report = `# Debugging difficulty results

Generated by \`debugging/measure.mjs\` from the scenarios in \`debugging/scenarios.mjs\`. Do not edit by hand.

The same seven mistakes, made with Nexo's lower-level APIs (**before**: \`createApplication\`,
hand-written modules, \`startHapiServer\`) and with \`serve()\`/\`resource()\`/\`model()\` (**after**).
For each: when the mistake was detected (${STAGES.map((s) => STAGE_TEXT[s]).join(" < ")}, best
first), and whether the message names the **cause**, **where** to change something, and how to
**fix** it. The criteria are the same for both variants, fixed per scenario before the first run.
A crossed-out criterion wasn't met. One criterion was corrected after the first run because it was
too narrow: "where" for the unprotected API required the text \`tasks\`, which the hand-written API's
name (\`createTask\`) doesn't contain; it now asks whether the API is named, which credits **before**.

Read the totals with the details below: for the port and database mistakes both variants pass
Node's own error through unchanged, and the \`missing-scope\` "fix" credit comes from the
\`missingScopes\` field naming what's missing, not from advice.

This measures what the framework tells a developer. How long people take to find and fix each
mistake needs people; see [TIME-PROTOCOL.md](./TIME-PROTOCOL.md).

| Mistake | Before | After |
|---|---|---|
${rows.join("\n")}
| **Total** | detected ${detected("before")}/${results.length}, ${earliest("before")} at startup, ${total("before")}/${results.length * 3} points | detected ${detected("after")}/${results.length}, ${earliest("after")} at startup, ${total("after")}/${results.length * 3} points |

## What each variant said

${details.join("\n")}`;
  await writeFile(join(here, "..", "DEBUGGING.md"), report);
  console.log(rows.join("\n"));
  console.log(`before: detected ${detected("before")}/${results.length}, ${total("before")} points; after: detected ${detected("after")}/${results.length}, ${total("after")} points`);
}
