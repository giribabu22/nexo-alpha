#!/usr/bin/env node
/**
 * Measures each feature's "before" and "after" source and writes RESULTS.md.
 *
 *   pnpm --filter @nexo/benchmark-code-to-intent measure
 *
 * Metrics (all computed from the files in src/<feature>/<variant>/):
 * - files:     source files the feature needs.
 * - LOC:       lines that are not blank and not only a comment.
 * - imports:   import statements.
 * - concepts:  distinct names imported from @nexo-alpha/* packages.
 * - shapes:    places a data shape is written out by hand: `interface X {`,
 *              a `properties` field list, or a `model(` call. Derived types
 *              (`Pick<…>`, `Infer<…>`) are not counted.
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const src = join(root, "src");

const FEATURES = [
  ["get-api", "GET API (backend)"],
  ["validated-post", "Authenticated + validated POST (backend)"],
  ["user-crud", "User CRUD (full stack: model, API, page with form + table)"],
  ["product-search", "Product search + filter + pagination (full stack)"],
  ["relationship", "Relationship: orders → customers (backend)"],
  ["authentication", "Authentication: register, login, logout, me + login page (full stack)"],
  ["file-upload", "File upload + safe download (backend)"]
];

function measureSource(text) {
  let loc = 0;
  let inBlockComment = false;
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (inBlockComment) {
      if (line.includes("*/")) inBlockComment = false;
      continue;
    }
    if (line === "" || line.startsWith("//")) continue;
    if (line.startsWith("/*")) {
      if (!line.includes("*/")) inBlockComment = true;
      continue;
    }
    loc++;
  }

  const imports = [...text.matchAll(/^import\s/gm)].length;
  const concepts = new Set();
  for (const match of text.matchAll(/import\s+(?:type\s+)?\{([^}]*)\}\s*from\s*"@nexo-alpha\/[^"]+"/g)) {
    for (const name of match[1].split(",")) {
      const clean = name.replace(/^\s*type\s+/, "").split(/\s+as\s+/)[0].trim();
      if (clean !== "") concepts.add(clean);
    }
  }
  const shapes =
    [...text.matchAll(/\binterface\s+\w+\s*\{/g)].length +
    [...text.matchAll(/\bproperties\s*[:=]/g)].length +
    [...text.matchAll(/\bmodel\(/g)].length;

  return { loc, imports, concepts, shapes };
}

async function measureVariant(feature, variant) {
  const dir = join(src, feature, variant);
  const files = (await readdir(dir)).filter((file) => /\.(ts|tsx)$/.test(file)).sort();
  const totals = { files: files.length, loc: 0, imports: 0, concepts: new Set(), shapes: 0, fileList: [] };
  for (const file of files) {
    const metrics = measureSource(await readFile(join(dir, file), "utf8"));
    totals.loc += metrics.loc;
    totals.imports += metrics.imports;
    totals.shapes += metrics.shapes;
    for (const concept of metrics.concepts) totals.concepts.add(concept);
    totals.fileList.push(`${file} (${metrics.loc})`);
  }
  return totals;
}

const pct = (before, after) => (before === 0 ? "—" : `${Math.round((1 - after / before) * 100)}%`);

const rows = [];
const sum = { before: { files: 0, loc: 0, imports: 0, shapes: 0 }, after: { files: 0, loc: 0, imports: 0, shapes: 0 } };
const details = [];

for (const [feature, title] of FEATURES) {
  const before = await measureVariant(feature, "before");
  const after = await measureVariant(feature, "after");
  for (const [variant, m] of [["before", before], ["after", after]]) {
    for (const key of ["files", "loc", "imports", "shapes"]) sum[variant][key] += m[key];
  }
  rows.push(
    `| ${title} | ${before.loc} → **${after.loc}** (−${pct(before.loc, after.loc)}) | ${before.files} → ${after.files} | ` +
    `${before.imports} → ${after.imports} | ${before.concepts.size} → ${after.concepts.size} | ${before.shapes} → ${after.shapes} |`
  );
  details.push(
    `### ${title}\n\n` +
    `- before: ${before.fileList.join(", ")}\n  concepts: ${[...before.concepts].sort().join(", ")}\n` +
    `- after: ${after.fileList.join(", ")}\n  concepts: ${[...after.concepts].sort().join(", ")}\n`
  );
}

const total =
  `| **Total** | ${sum.before.loc} → **${sum.after.loc}** (−${pct(sum.before.loc, sum.after.loc)}) | ${sum.before.files} → ${sum.after.files} | ` +
  `${sum.before.imports} → ${sum.after.imports} | | ${sum.before.shapes} → ${sum.after.shapes} |`;

const report = `# Code-to-intent results

Generated by \`measure.mjs\` from the sources in \`src/\`. Do not edit by hand.

Each feature is written twice, with the APIs that existed before \`model()\`/\`resource()\`
(**before**) and with them (**after**). Both backends pass the same HTTP checks in
\`test/conformance.test.js\` (status codes, validation, defaults, 404s, auth scopes, paging).
Where the two differ, **after** does more: it serves full CRUD where **before** only has the
endpoints the feature needs, rejects unknown fields, validates forms in the browser, shows
errors next to their fields, and refreshes lists after any write. For authentication, **after**
also claims emails atomically, takes as long for unknown emails as for wrong passwords, limits
failed sign-ins, offers sign-up in the form, and signs the client out when the server ends a session.
File upload is the one feature whose requests differ: **before**, handlers only received parsed
JSON, so files travel base64-encoded (about 33% larger, and capped near 750 KB by the default 1 MB
body limit); **after** sends the raw bytes. Everything checked after the upload is identical.

| Feature | LOC | Files | Imports | Framework concepts | Hand-written shapes |
|---|---|---|---|---|---|
${rows.join("\n")}
${total}

**Metrics.** LOC: lines that are not blank and not only a comment. Concepts: distinct names
imported from \`@nexo-alpha/*\`. Hand-written shapes: \`interface X {\`, \`properties\` field
lists and \`model(\` calls, i.e. places the shape of data is spelled out; derived types such
as \`Pick<…>\` and \`Infer<…>\` are not counted.

## Per file

${details.join("\n")}`;

await writeFile(join(root, "RESULTS.md"), report);
console.log(rows.join("\n"));
console.log(total);
